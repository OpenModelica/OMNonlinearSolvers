//! A generic C interface of the homotopy solver.
//!
//! A C host creates a [`HomSolver`] with [`hom_solver_new`], describes its
//! system as a [`HomModel`] of callbacks and solves it with [`hom_solve`] or
//! [`hom_solve_own_homotopy`]. The header `include/openmodelica_homotopy_capi.h` is
//! generated by `cbindgen` when the crate is built.
//!
//! The interface knows nothing about the host. The glue to the OpenModelica C
//! runtime, `NONLINEAR_SYSTEM_DATA`, the asserts of its models, mixed systems
//! and its flags, lives in OpenModelica and uses this interface.
//!
//! All `unsafe` code of the project belongs in this crate.

mod exports;
mod logger;
mod model;
mod observer;
mod settings;

pub use exports::{
    HomSolvedBy, HomSolver, HomStatistics, HomStatus, hom_solve, hom_solve_own_homotopy,
    hom_solver_free, hom_solver_new, hom_solver_statistics,
};
pub use logger::{HomLogLevel, HomLogger, hom_set_logger};
pub use model::{
    HOM_EVAL_ASSERT, HOM_EVAL_CONSTRAINT_VIOLATED, HOM_EVAL_OK, HomFallback, HomJacobian, HomModel,
    HomResidual,
};
pub use observer::{
    HomObserver, HomPathFailed, HomPathFailure, HomPathFinished, HomPathStarted, HomStepAccepted,
    HomStepStarted,
};
pub use settings::HomSettings;
